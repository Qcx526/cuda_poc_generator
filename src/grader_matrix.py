# -*- coding: utf-8 -*-
"""Run every declared tool over every produced artifact, inside the container.

The candidate decides what to craft; it must not decide what gets executed.
When the candidate ran its own matrix, a run that never invoked the crashing
tool looked identical to a run whose input simply did not trigger - and one
specification even named the wrong tool. Executing from the declared
invocations removes both problems: the tool list is data from the
specification, and every artifact meets every tool the same way.

The emitted lines are the ones the grader already parses:

    [CPG_RUN] benign.cubin::nvdisasm exit=0
"""

import shlex
from typing import List, Optional, Sequence

ARTIFACT_GLOBS = ("*.cubin", "*.elf", "*.fatbin", "/tmp/*.cubin", "/tmp/*.elf")
# Undeclared artifacts are a fallback, not the plan. A sweep of hundreds of
# variants once held one run in the container for twenty-four minutes; the cap
# keeps a missing manifest from turning into a missing afternoon.
FALLBACK_LIMIT = 12


def tool_name(invocation: Sequence[str]) -> str:
    """A short, stable label for an invocation template."""
    if not invocation:
        return "tool"
    return str(invocation[0]).rsplit("/", 1)[-1]


def parse_invocations(anchor_invocations: Optional[Sequence[Sequence[str]]],
                      anchor_invocation: Optional[Sequence[str]]) -> List[List[str]]:
    """Normalise both schema forms into a list of argv templates.

    ``invocations`` is the general form; ``invocation`` is the single-tool form
    every older specification uses and must keep working unchanged.
    """
    if anchor_invocations:
        return [list(item) for item in anchor_invocations if item]
    if anchor_invocation:
        return [list(anchor_invocation)]
    return []


def _crashcap_header() -> list:
    """Compile the recording shim in place, or carry on without it.

    Building it at run time keeps the image unchanged; gcc is only needed once,
    and a failure just means the fingerprint degrades to the exit code.
    """
    return [
        "crashcap=''",
        "if [ ! -f ./crashcap.so ] && [ -f ./crashcap.c ] && command -v gcc >/dev/null 2>&1; then",
        "  gcc -shared -fPIC -O1 -o ./crashcap.so ./crashcap.c -ldl >/dev/null 2>&1 || true",
        "fi",
        "[ -f ./crashcap.so ] && crashcap='./crashcap.so'",
    ]


def _invocation_lines(invocation, indent: str) -> list:
    """Run one tool on $artifact and record where it faulted, if it did."""
    name = tool_name(invocation)
    parts = []
    for part in invocation:
        parts.append('"$artifact"' if str(part) == "{artifact}"
                     else shlex.quote(str(part)))
    command = " ".join(parts)
    return [
        '%srm -f ".cc.$base"' % indent,
        '%sCRASHCAP_OUT=".cc.$base" LD_PRELOAD="$crashcap" %s > /dev/null 2>&1'
        % (indent, command),
        "%src=$?" % indent,
        '%secho "[CPG_RUN] $base::%s exit=$rc"' % (indent, name),
        '%sif [ -f ".cc.$base" ]; then sed "s/^/[CPG_CRASH] $base /" ".cc.$base"; rm -f ".cc.$base"; fi'
        % indent,
    ]


def render_matrix_script(invocations: Sequence[Sequence[str]],
                         entries: Optional[Sequence[Sequence[str]]] = None) -> str:
    """A POSIX shell script that exercises artifacts with the declared tools.

    Shell because the image has nothing installed, and unrolled at generation
    time so the script contains no parsing of its own - a quoting bug in a
    generator is invisible until a CVE silently reports the wrong tool.
    """
    lines = ["#!/bin/sh",
             "# Generated by grader_matrix: same artifacts, same tools, every run."]
    lines.extend(_crashcap_header())
    if entries:
        # Declared artifacts only: a sweep of intermediate files is the
        # candidate's business and must not decide what the verdict reads.
        for name, role in entries:
            lines.append("echo '[CPG_LABEL] %s %s'" % (name, role))
        lines.append("for artifact in %s; do"
                     % " ".join(shlex.quote(name) for name, _ in entries))
        lines.append("  [ -f \"$artifact\" ] || continue")
        lines.append("  base=$(basename \"$artifact\")")
        for invocation in invocations:
            lines.extend(_invocation_lines(invocation, "  "))
        lines.append("done")
        lines.append("true")
        return "\n".join(lines) + "\n"
    # Undeclared artifacts still get labelled, by prefix only. Without labels the
    # grader cannot assign roles at all and reports "nothing to grade" even after
    # a genuine crash; with guessed labels it can at least say which file was
    # meant as what, and UNKNOWN never counts toward a verdict.
    lines.append("role_of() {")
    lines.append("  case \"$1\" in")
    lines.append("    benign*) echo BENIGN ;;")
    lines.append("    ctrl*|control*) echo CONTROL ;;")
    lines.append("    poc*|crafted*|malicious*|trigger*) echo MALICIOUS ;;")
    lines.append("    *) echo UNKNOWN ;;")
    lines.append("  esac")
    lines.append("}")
    lines.append("count=0")
    for glob in ARTIFACT_GLOBS:
        lines.append("for artifact in %s; do" % glob)
        lines.append("  count=$((count + 1)); [ \"$count\" -gt %d ] && continue"
                     % FALLBACK_LIMIT)
        lines.append("  [ -f \"$artifact\" ] || continue")
        lines.append("  base=$(basename \"$artifact\")")
        # No backslash before the quotes: inside the double-quoted echo those
        # would reach role_of as literal quote characters, and every artifact
        # would be labelled UNKNOWN.
        lines.append('  echo "[CPG_LABEL] $base $(role_of "$base")"')
        for invocation in invocations:
            lines.extend(_invocation_lines(invocation, "  "))
        lines.append("done")
    lines.append("true")
    return "\n".join(lines) + "\n"
