"""Immutable native-tool setup body; imported only by the controlled runner.

The command supplied to this body is generated by cuda_registry, never by a
request or model. The parent additionally validates the first and subsequent
kernel exec stops before allowing instructions in a tool image to execute.
"""


CUDA_GUARD_SOURCE = b'''"""Fixed P2-C resource-gated native CUDA tool launcher; never starts a kernel."""
import ctypes
import hashlib
import json
import os
import resource
import signal
import socket
import stat
import sys

config = json.loads(sys.stdin.buffer.read(65537))
required = {"request_id", "nonce", "cpu_seconds", "memory_bytes", "control_fd", "parent_pid",
            "tool_path", "tool_sha256", "argv", "environment"}
if set(config) != required:
    raise ValueError("invalid fixed CUDA guard configuration")
if (type(config["cpu_seconds"]) is not int or not 1 <= config["cpu_seconds"] <= 60
        or type(config["memory_bytes"]) is not int or not 1073741824 <= config["memory_bytes"] <= 8589934592
        or type(config["control_fd"]) is not int or config["control_fd"] < 3
        or type(config["parent_pid"]) is not int or config["parent_pid"] < 1):
    raise ValueError("invalid fixed CUDA guard resource bounds")
for name in ("request_id", "nonce"):
    if (not isinstance(config[name], str) or len(config[name]) != 32
            or any(char not in "0123456789abcdef" for char in config[name])):
        raise ValueError("invalid fixed CUDA guard identity")
if (not isinstance(config["tool_path"], str) or not config["tool_path"].startswith("/")
        or not isinstance(config["tool_sha256"], str) or len(config["tool_sha256"]) != 64
        or not isinstance(config["argv"], list) or not config["argv"]
        or config["argv"][0] != config["tool_path"]
        or any(not isinstance(arg, str) or "\\0" in arg for arg in config["argv"])
        or not isinstance(config["environment"], dict)):
    raise ValueError("invalid fixed CUDA tool plan")
libc = ctypes.CDLL(None, use_errno=True)
libc.ptrace.restype = ctypes.c_long
if libc.prctl(1, signal.SIGKILL, 0, 0, 0) != 0:
    raise OSError(ctypes.get_errno(), "PR_SET_PDEATHSIG failed")
parent_signal = ctypes.c_int()
if (libc.prctl(2, ctypes.byref(parent_signal), 0, 0, 0) != 0
        or parent_signal.value != signal.SIGKILL or os.getppid() != config["parent_pid"]):
    raise RuntimeError("trusted parent identity or parent-death signal unknown")
resource.setrlimit(resource.RLIMIT_CPU, (config["cpu_seconds"],) * 2)
resource.setrlimit(resource.RLIMIT_AS, (config["memory_bytes"],) * 2)
if (resource.getrlimit(resource.RLIMIT_CPU) != (config["cpu_seconds"],) * 2
        or resource.getrlimit(resource.RLIMIT_AS) != (config["memory_bytes"],) * 2):
    raise RuntimeError("fixed CUDA guard resource limits were not applied")
control = socket.socket(fileno=config["control_fd"])
def notify(message):
    message.update(request_id=config["request_id"], nonce=config["nonce"])
    control.sendall((json.dumps(message, sort_keys=True, separators=(",", ":")) + "\\n").encode("utf-8"))
with open("/proc/self/stat", "r", encoding="ascii") as stream:
    start_ticks = int(stream.read().rsplit(") ", 1)[1].split()[19])
tool_fd = os.open(config["tool_path"], os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
before = os.fstat(tool_fd)
if not stat.S_ISREG(before.st_mode) or before.st_mode & (stat.S_ISUID | stat.S_ISGID):
    raise RuntimeError("native CUDA tool must be a nonprivileged regular executable")
digest = hashlib.sha256()
first = True
while True:
    block = os.read(tool_fd, 1048576)
    if not block:
        break
    if first and not block.startswith(b"\\x7fELF"):
        raise RuntimeError("script/native CUDA tool variant is unsupported")
    first = False
    digest.update(block)
after = os.fstat(tool_fd)
if (first or digest.hexdigest() != config["tool_sha256"]
        or (before.st_dev,before.st_ino,before.st_size,before.st_mtime_ns,before.st_ctime_ns)
        != (after.st_dev,after.st_ino,after.st_size,after.st_mtime_ns,after.st_ctime_ns)):
    raise RuntimeError("pinned native CUDA tool identity changed")
if os.execve not in os.supports_fd:
    notify({"event": "NATIVE_UNSUPPORTED", "reason": "fd-pinned execve unsupported"})
    sys.exit(120)
notify({"event": "RESOURCE_READY", "pid": os.getpid(), "pgid": os.getpgrp(),
        "session_id": os.getsid(0), "start_ticks": start_ticks,
        "cpu_seconds": config["cpu_seconds"], "memory_bytes": config["memory_bytes"],
        "parent_pid": config["parent_pid"], "parent_death_signal": parent_signal.value})
control.settimeout(5)
gate = b""
while len(gate) < 3:
    block = control.recv(3 - len(gate))
    if not block:
        break
    gate += block
if gate != b"GO\\n":
    raise RuntimeError("trusted parent did not authorize the native tool gate")
if libc.ptrace(0, 0, 0, 0) != 0:
    notify({"event": "NATIVE_UNSUPPORTED", "reason": "PTRACE_TRACEME unavailable"})
    sys.exit(120)
control.close()
os.execve(tool_fd, config["argv"], config["environment"])
'''
